"""Numbers and tables for the paper, from the results of scripts 02-07 (Ridom is the source of truth).

Reads output/kansasii-ridom/results/ and writes there:
  paper_species_table.tsv  per species: isolates, references, good targets, genome size, allele distances within the species
                           (median, range over isolate pairs, references left out), clusters. M055 (sent to Ridom, but
                           excluded from the distance analysis by Ridom) is not counted: the table covers the cohort only
  paper_numbers.md         the figures of the methods / results as sentences with their source file
Run after 02-07 (submit_all.sbatch does).
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

from common import DISTANCE_SUBSETS
from kansasii_paths import OUT_RIDOM


def fmt_range(median: float, lo: float, hi: float, digits: int = 1) -> str:
    return f"{median:.{digits}f} ({lo:.{digits}f}-{hi:.{digits}f})"


def species_table(qc: pd.DataFrame, dist_summary: pd.DataFrame, clusters: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for sp in [s for s in DISTANCE_SUBSETS if s not in ("complex", "minor") and s in set(dist_summary.subset)]:
        g = qc[qc.species == sp]
        iso = g[(g.kind == "isolate") & (g.cohort == "keep")]
        d = dist_summary[dist_summary.subset == sp].iloc[0]
        c = clusters[(clusters.species == sp) & (clusters.kind == "isolate")]
        rows.append({
            "species": sp, "isolates": len(iso), "references": int((g.kind == "reference").sum()),
            "good_targets_pct": fmt_range(iso.good_targets_pct.median(), iso.good_targets_pct.min(), iso.good_targets_pct.max()) if len(iso) else "",
            "genome_mbases": fmt_range(iso.genome_mbases.median(), iso.genome_mbases.min(), iso.genome_mbases.max()) if len(iso) else "",
            "distance_median": d["study_median"], "distance_min": d["study_min"], "distance_max": d["study_max"],
            "identical_pairs": d.study_identical_pairs,
            "clustered_isolates": int((c.cluster != "singleton").sum()), "clusters": c[c.cluster != "singleton"].cluster.nunique(),
            "singletons": int((c.cluster == "singleton").sum()),
        })
    return pd.DataFrame(rows)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results", type=Path, default=OUT_RIDOM / "results")
    a = ap.parse_args()
    r = a.results
    need = ["qc.tsv", "distance_summary.tsv", "clusters.tsv", "cluster_threshold.tsv", "scheme_summary.tsv", "control_distances.tsv", "locus_stats.tsv"]
    absent = [f for f in need if not (r / f).exists()]
    if absent:
        print(f"ERROR: run scripts 02-07 first, missing in {r}: {', '.join(absent)}", file=sys.stderr)
        return 1
    qc = pd.read_csv(r / "qc.tsv", sep="\t")
    ds = pd.read_csv(r / "distance_summary.tsv", sep="\t")
    cl = pd.read_csv(r / "clusters.tsv", sep="\t")
    th = pd.read_csv(r / "cluster_threshold.tsv", sep="\t")
    sc = pd.read_csv(r / "scheme_summary.tsv", sep="\t", dtype=str, keep_default_na=False).set_index("key")["value"]
    ctl = pd.read_csv(r / "control_distances.tsv", sep="\t")
    loc = pd.read_csv(r / "locus_stats.tsv", sep="\t")

    tab = species_table(qc, ds, cl)
    tab.to_csv(r / "paper_species_table.tsv", sep="\t", index=False)
    iso = qc[qc.kind != "reference"]
    t = th[th.same_as_ridom]
    thr = f"{int(t.threshold.min())}" if len(t) == 1 else f"{int(t.threshold.min())}-{int(t.threshold.max())}"
    clustered = cl[(cl.kind != "reference") & (cl.cluster != "singleton")]
    n_cl = int((cl.kind != "reference").sum())  # M055 (pool only) has a QC value but no distances / cluster
    complex_ = ds[ds.subset == "complex"].iloc[0]
    lines = [
        "# Numbers for the paper (generated by scripts/08_paper_numbers.py, do not edit)", "",
        "## cgMLST scheme (scheme_summary.tsv)",
        f"- Scheme: {sc['scheme_name']}; SeqSphere+ / Ridom Typer {sc['ridom_typer_version']}, cgMLST Target Definer {sc['target_definer_version']}, run {sc['target_definer_date']}.",
        f"- Seed genome {sc['seed_genome']}; {sc['n_query_genomes']} penetration query genomes; {sc['n_exclude_sequences']} exclude sequences (plasmids).",
        f"- Target filters: minimum length {sc['min_target_length_bp']} bp; BLAST overlap {sc['blast_overlap_pct']}% and identity >= {sc['blast_identity_min_pct']}% in every query genome; "
        f"single stop codon in > {sc['stop_codon_penetration_pct']}% of the query genomes.",
        f"- {sc['n_core_targets']} core targets ({int(sc['core_bases']):,} bases, {sc['seed_genome_coverage_pct']}% of the seed genome, median {sc['core_target_length_median_bp']} bp), "
        f"{sc['n_accessory_targets']} accessory targets, {sc['n_discarded_targets']} discarded.", "",
        "## Isolates (qc.tsv, qc_summary.tsv)",
        f"- {len(iso)} genomes typed (QC; {n_cl} in the distance analysis, the rest is excluded by coverage), plus {int((qc.kind == 'reference').sum())} public references.",
        f"- Good targets: median {iso.good_targets_pct.median():.1f}% (range {iso.good_targets_pct.min():.1f}-{iso.good_targets_pct.max():.1f}%); "
        f"genome size median {iso.genome_mbases.median():.1f} Mb (range {iso.genome_mbases.min():.1f}-{iso.genome_mbases.max():.1f}).",
        f"- {int((loc.n_missing == 0).sum())} of {len(loc)} targets were called in every genome; {int((loc.n_alleles <= 1).sum())} are monomorphic.", "",
        "## Allele distances (distance_summary.tsv)",
        f"- Complex ({int(complex_.n)} genomes): median {complex_['median']:g}, range {complex_['min']:g}-{complex_['max']:g} alleles; {int(complex_.identical_pairs)} identical pairs "
        "(missing values: pairwise ignore).", "",
        "## Clusters (clusters.tsv, cluster_threshold.tsv)",
        f"- MST clusters = single linkage at <= {thr} allele differences (reproduces Ridom's grouping exactly): "
        f"{clustered.cluster.nunique()} clusters containing {len(clustered)} of {n_cl} isolates in the distance analysis; {int(((cl.kind != 'reference') & (cl.cluster == 'singleton')).sum())} singletons.", "",
        "## Controls (control_distances.tsv)",
    ]
    for _, g in ctl[ctl.comparator_kind == "reference"].iterrows():
        lines.append(f"- {g.control} vs {g.comparator}: {g.distance} alleles.")
    (r / "paper_numbers.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(tab.to_string(index=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
